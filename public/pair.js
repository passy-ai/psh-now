// psh.now - pair a device from a link (/pair/:code).

// migrate keys written under the old brand name
for (const k of ["deviceToken", "workspace", "demoApiKey", "notifyAsked"]) {
  const old = localStorage.getItem(`pshy.${k}`);
  if (old && !localStorage.getItem(`psh.${k}`)) localStorage.setItem(`psh.${k}`, old);
}

const K = { token: "psh.deviceToken", workspace: "psh.workspace" };

const titleEl = document.getElementById("title");
const messageEl = document.getElementById("message");
const pairForm = document.getElementById("pairForm");
const nameInput = document.getElementById("deviceName");
const pairBtn = document.getElementById("pairBtn");
const toastEl = document.getElementById("toast");

function toast(msg) {
  toastEl.textContent = msg;
  toastEl.classList.add("show");
  clearTimeout(toast._t);
  toast._t = setTimeout(() => toastEl.classList.remove("show"), 2400);
}

const token = location.pathname.split("/").filter(Boolean).pop();

function deviceName() {
  const ua = navigator.userAgent;
  if (/iPhone/i.test(ua)) return "iPhone";
  if (/iPad/i.test(ua)) return "iPad";
  if (/Android/i.test(ua)) return "Android";
  if (/Macintosh/i.test(ua)) return "Mac";
  return "Device";
}

async function init() {
  if (!token) {
    titleEl.textContent = "Invalid link";
    messageEl.textContent = "Open the full link generated by psh.";
    return;
  }
  try {
    const res = await fetch(`/api/v1/pairing/${encodeURIComponent(token)}`);
    if (!res.ok) {
      titleEl.textContent = "Link expired";
      messageEl.textContent = "This link is invalid, expired, or already used.";
      return;
    }
    const data = await res.json();
    // Name the person, not the workspace id - this reads like an invite.
    const who = data.ownerName || data.workspaceName || "a psh.now account";
    titleEl.textContent = `Join ${who}`;
    messageEl.textContent = data.channelName
      ? `Pair this device to approve \u201c${data.channelName}\u201d and the rest of the account.`
      : "Pair this device to receive approvals.";
    nameInput.value = deviceName();
    pairForm.classList.remove("hide");
    nameInput.focus();
  } catch {
    titleEl.textContent = "Can't reach psh.now";
    messageEl.textContent = "Check your connection and reload.";
  }
}

pairBtn?.addEventListener("click", async () => {
  const name = nameInput.value.trim() || deviceName();
  pairBtn.disabled = true;
  pairBtn.innerHTML = `<span class="spinner"></span> Pairing…`;
  try {
    const res = await fetch(`/api/v1/pairing/${encodeURIComponent(token)}/claim`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ name }),
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.message || "Pairing failed");

    // This device belongs to the paired ACCOUNT. Drop any account key this
    // browser was holding, or the app would keep using it and look like a
    // separate (anonymous) workspace.
    localStorage.removeItem("psh.apiKey");
    localStorage.setItem(K.token, data.deviceToken);
    localStorage.setItem(K.workspace, JSON.stringify({ id: data.workspaceId, name: data.workspaceId }));
    titleEl.textContent = "Paired";
    messageEl.textContent = "Opening your dashboard…";
    setTimeout(() => (location.href = "/app?welcome=1"), 600);
  } catch (err) {
    toast(err.message || "Pairing failed");
    pairBtn.disabled = false;
    pairBtn.textContent = "Pair this device";
  }
});

init();